def parse_sections(lines):
    start = next(i + 1 for i, line in enumerate(lines) if line == "<!-- TOC END -->")
    sections, current = OrderedDict(), None
    for line in lines[start:]:
        if line.startswith("## "):
            current = line[3:]
            sections[current] = []
        elif current is not None:
            sections[current].append(line)
    return sections


def clean_content(content):
    content = list(content)
    while content and not content[0].strip():
        content.pop(0)
    while content and not content[-1].strip():
        content.pop()
    if content and re.match(r"> \*\*PDF .+쪽", content[0]):
        content = content[1:]
        while content and not content[0].strip():
            content.pop(0)
    return content


def keyword_block(items):
    out = ["## 주요 단어 먼저 보기", "", "| 주요 단어 | 뜻 |", "|---|---|"]
    out += [f"| {term} | {meaning} |" for term, meaning in items]
    out += ["", "> **단원 시작법:** 주요 단어의 뜻을 먼저 읽고, 아래 PDF 절 순서대로 학습한다.", ""]
    return out


def main():
    for chapter, cfg in CONFIG.items():
        path = next(NOTES.glob(f"{chapter:02d}_*.md"))
        lines = path.read_text(encoding="utf-8").splitlines()
        title = lines[0]
        source = next(line for line in lines if line.startswith("> 원본 PDF 범위:"))
        source = source.split(" · ")[0] + " · PDF 설명 순서에 따라 재작성"
        sections = parse_sections(lines)

        numbered = []
        for label in sections:
            match = re.match(r"^(\d+)\. ", label)
            if match:
                numbered.append((int(match.group(1)), label))
        numbered.sort()

        theory = [(n, label) for n, label in numbered if "교재 문제" not in label]
        if len(theory) != len(cfg["pages"]):
            raise ValueError(f"{path.name}: theory={len(theory)}, pages={len(cfg['pages'])}")

        problem_label = next((x for x in sections if "교재 문제와 해설" in x), None)
        if not problem_label:
            raise ValueError(f"{path.name}: problem section missing")

        supplements = [x for x in sections if x in ("보충 학습", "추가 보충")]
        used = {label for _, label in theory} | {problem_label} | set(supplements) | {"목차"}
        remainder = [x for x in sections if x not in used]

        out = [title, "", source, ""]
        out += keyword_block(cfg["keywords"])
        out += ["<!-- TOC START -->", "## 목차", "", "<!-- TOC END -->", ""]

        memories = []
        for (_, label), pages in zip(theory, cfg["pages"]):
            content = clean_content(sections[label])
            memories += [line.replace("> **암기 한 줄:** ", "- ") for line in content if line.startswith("> **암기 한 줄:**")]
            out += ["## " + label, "", f"> **PDF {pages}쪽**", ""] + content + [""]

        qnum, qpages = cfg["q"]
        qcontent = clean_content(sections[problem_label])
        out += [f"## {qnum}. 교재 문제와 해설", "", f"> **PDF {qpages}쪽 · 원문 출제 순서**", ""] + qcontent + [""]

        for label in supplements + remainder:
            content = clean_content(sections[label])
            out += ["## " + label, ""] + content + [""]

        if memories:
            out += ["## 시험 직전 암기", ""] + memories + [""]

        path.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
        print(path.name)


if __name__ == "__main__":
    main()
