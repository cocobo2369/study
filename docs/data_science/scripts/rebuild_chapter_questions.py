def render_related(related):
    return " · ".join("[{}]({})".format(title, anchor) for title, anchor in related)


def render_section(chapter, questions):
    question_heading_number = None
    path = NOTES / FILES[chapter]
    text = path.read_text(encoding="utf-8")
    match = re.search(r"(?m)^## (\d+)\. 교재 문제와 해설\s*$", text)
    if not match:
        raise RuntimeError("Question heading not found in {}".format(path))
    question_heading_number = match.group(1)

    lines = [
        "## {}. 교재 문제와 해설".format(question_heading_number), "",
        "> **원문 단원 말미 문제 전체 수록**", "",
        "> 먼저 문제와 보기를 풀고, **정답 및 선택지별 해설 보기**를 펼쳐 확인하세요. 일반 4지선다 문항은 ①~④를 모두 해설하며, 원문이 2지선다인 경우에는 실제 보기만 수록합니다.", "",
        "### 문제 바로가기", "",
        "| 문제 | 주제 | 관련 목차 | PDF |", "|---:|---|---|---:|",
    ]
    for index, item in enumerate(questions, start=1):
        lines.append(
            "| [{}](#ch{:02d}-q{}) | {} | {} | {}쪽 |".format(
                index, chapter, index, item["title"], render_related(item["related"]), item["page"]
            )
        )

    for index, item in enumerate(questions, start=1):
        lines.extend([
            "", '<a id="ch{:02d}-q{}"></a>'.format(chapter, index), "",
            "### 문제 {}. {}".format(index, item["title"]), "",
            "**출처:** PDF {}쪽  ".format(item["page"]),
            "**관련 목차:** {}".format(render_related(item["related"])), "",
            item["stem"], "",
        ])
        if item.get("asset"):
            lines.extend([
                "![문제 {}에 필요한 교재 그림]({})".format(index, item["asset"]), "",
            ])
        if item.get("note"):
            lines.extend(["> **문항 주의:** {}".format(item["note"]), ""])
        for option_number, option in enumerate(item["options"], start=1):
            lines.append("{}. {}".format(option_number, option))

        lines.extend(["", "<details>", "<summary>정답 및 선택지별 해설 보기</summary>", "",
                      "**정답: {} {}**".format(CIRCLED[item["answer"] - 1], item["options"][item["answer"] - 1]), ""])
        for option_number, rationale in enumerate(item["rationales"], start=1):
            verdict = "정답" if option_number == item["answer"] else "오답"
            rationale = re.sub(r"^(?:정답|오답)\.\s*", "", rationale)
            lines.append("- **{} {}:** {}".format(CIRCLED[option_number - 1], verdict, rationale))
        lines.extend(["", "</details>"])

    return "\n".join(lines) + "\n", text


def replace_section(chapter, questions):
    section, text = render_section(chapter, questions)
    pattern = re.compile(
        r"(?ms)^## \d+\. 교재 문제와 해설\s*\n.*?(?=^## )"
    )
    updated, count = pattern.subn(section + "\n", text, count=1)
    if count != 1:
        raise RuntimeError("Could not replace question section in {}".format(FILES[chapter]))
    with (NOTES / FILES[chapter]).open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(updated)
    print("chapter {:02d}: {} questions".format(chapter, len(questions)))


def main():
    for chapter in sorted(BANK):
        if len(BANK[chapter]) != 5:
            raise RuntimeError("Chapter {} does not contain five questions".format(chapter))
        replace_section(chapter, BANK[chapter])


if __name__ == "__main__":
    main()
